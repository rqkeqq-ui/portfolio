// Static export of the Next.js projects into public/projects/<slug>/app/.
//
//   node tools/export-next-demos.mjs              export every project
//   node tools/export-next-demos.mjs fixflow      export one project
//
// The source repository is never modified: each project is copied to a temporary
// folder (its node_modules is linked, not copied), patched for `output: 'export'`
// and built there. Pages are served under DEMO_BASE (default /portfolio — the
// GitHub Pages path); the Vite dev server maps /portfolio/* onto the site root,
// so the same export also works locally.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs';
import { join, resolve, extname } from 'node:path';
import { homedir, tmpdir } from 'node:os';
import { execSync } from 'node:child_process';

const root = resolve(import.meta.dirname, '..');
const desktop = join(homedir(), 'Desktop', 'Проекты');
const siteBase = process.env.DEMO_BASE ?? '/portfolio';

const projects = {
  'weekly-table': { source: join(desktop, 'WEEKLY TABLE') },
  fixflow: { source: join(desktop, 'Fixflow'), patch: patchFixflow },
  // Turbopack (Next 16 default) refuses a linked node_modules, so this one builds with webpack.
  northcut: { source: resolve(root, '..', 'work', 'Northcut'), buildArgs: '--webpack' }
};

const skip = new Set(['node_modules', '.next', 'out', 'dist', 'build', '.git', '.claude', '.wrangler', '.vinext', 'outputs', 'work', 'tests', 'docs', 'examples', 'worker', 'db', 'drizzle']);

function copyProject(from, to) {
  mkdirSync(to, { recursive: true });
  for (const name of readdirSync(from)) {
    if (skip.has(name)) continue;
    const source = join(from, name);
    if (statSync(source).isDirectory()) copyProject(source, join(to, name));
    else cpSync(source, join(to, name));
  }
}

function walk(dir, visit) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) { if (name !== 'node_modules') walk(path, visit); }
    else visit(path);
  }
}

function edit(path, transform) {
  const before = readFileSync(path, 'utf8');
  const after = transform(before);
  if (after === before) throw new Error(`patch did not apply: ${path}`);
  writeFileSync(path, after);
}

// next.config: static export under the demo base path.
function writeNextConfig(dir, basePath) {
  for (const name of ['next.config.ts', 'next.config.mjs', 'next.config.js']) rmSync(join(dir, name), { force: true });
  writeFileSync(join(dir, 'next.config.mjs'), `/** Generated by tools/export-next-demos.mjs */
export default {
  output: 'export',
  basePath: ${JSON.stringify(basePath)},
  trailingSlash: true,
  reactStrictMode: true,
  poweredByHeader: false,
  images: { unoptimized: true },
  eslint: { ignoreDuringBuilds: true },
  typescript: { ignoreBuildErrors: true }
};
`);
}

// Plain "/images/..." strings and CSS url(/...) skip Next's basePath handling, so prefix them by hand.
function prefixPublicPaths(dir, basePath) {
  const publicDir = join(dir, 'public');
  if (!existsSync(publicDir)) return;
  const entries = readdirSync(publicDir).map(name => name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  if (!entries.length) return;
  const pattern = new RegExp(`(["'\`(])/(${entries.join('|')})(?=[/"'\`)?#])`, 'g');
  walk(dir, path => {
    if (path.includes(`${join(dir, 'public')}`) || !['.ts', '.tsx', '.js', '.jsx', '.css', '.mjs'].includes(extname(path))) return;
    const text = readFileSync(path, 'utf8');
    const next = text.replace(pattern, `$1${basePath}/$2`);
    if (next !== text) writeFileSync(path, next);
  });
}

// Fixflow: the three API routes become an in-browser demo backend built from the same lib/ modules.
function patchFixflow(dir) {
  rmSync(join(dir, 'app', 'api'), { recursive: true, force: true });
  writeFileSync(join(dir, 'lib', 'demo-api.ts'), `// Generated by tools/export-next-demos.mjs: static-export stand-in for app/api/*.
import { buildSchedule, describeWindow } from './schedule';
import { lookupOrder } from './orders';
import { findCategory } from './catalog';

let orderCounter = 4902;
const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json' } });
const wait = () => new Promise((done) => setTimeout(done, 350));

export async function demoFetch(input: string, init?: RequestInit): Promise<Response> {
  await wait();
  const url = new URL(input, 'https://demo.local');
  if (url.pathname === '/api/slots') return json({ days: buildSchedule(5) });
  if (url.pathname === '/api/track') {
    const result = lookupOrder(url.searchParams.get('order') ?? '', url.searchParams.get('phone') ?? '');
    return result.ok
      ? json({ order: result.order })
      : json({ error: 'Заказ не найден. Проверьте номер и последние 4 цифры телефона.' }, 404);
  }
  if (url.pathname === '/api/leads') {
    const payload = JSON.parse(String(init?.body ?? '{}'));
    const category = typeof payload.category === 'string' ? findCategory(payload.category) : undefined;
    const text = (value: unknown) => (typeof value === 'string' ? value.trim() : '');
    const phone = text(payload.phone).replace(/\\D/g, '');
    if (!category) return json({ error: 'Не выбрана категория услуги' }, 422);
    if (text(payload.problem).length < 10) return json({ error: 'Слишком короткое описание проблемы' }, 422);
    if (text(payload.address).length < 5) return json({ error: 'Укажите адрес визита' }, 422);
    if (text(payload.name).length < 2) return json({ error: 'Укажите имя' }, 422);
    if (phone.length !== 11) return json({ error: 'Проверьте номер телефона' }, 422);
    if (!payload.slot) return json({ error: 'Не выбрано окно визита' }, 422);
    orderCounter += 1;
    return json({ orderNumber: orderCounter, windowLabel: describeWindow(payload.slot), demo: true });
  }
  return json({ error: 'Not found' }, 404);
}
`);
  edit(join(dir, 'components', 'request', 'RequestWizard.tsx'), text => text
    .replace("fetch('/api/slots')", "demoFetch('/api/slots')")
    .replace("await fetch('/api/leads',", "await demoFetch('/api/leads',")
    .replace(/(\n)(import [^\n]+\n)(?!import )/, `$1$2import { demoFetch } from '../../lib/demo-api';\n`));
  edit(join(dir, 'components', 'track', 'TrackForm.tsx'), text => text
    .replace('await fetch(`/api/track?${params}`)', 'await demoFetch(`/api/track?${params}`)')
    .replace("import { trackDemoHint } from '../../lib/orders';", "import { trackDemoHint } from '../../lib/orders';\nimport { demoFetch } from '../../lib/demo-api';")
    .replace('    if (initialOrder) setOrderNumber(initialOrder);',
      "    const fromUrl = initialOrder || new URLSearchParams(window.location.search).get('order') || '';\n    if (fromUrl) setOrderNumber(fromUrl);"));
  // A static page cannot read searchParams on the server; TrackForm reads ?order= in the browser instead.
  edit(join(dir, 'app', 'track', 'page.tsx'), text => text
    .replace(/export default async function TrackPage\(\{[\s\S]*?\}\) \{\n  const \{ order \} = await searchParams;\n/, 'export default function TrackPage() {\n')
    .replace("<TrackForm initialOrder={order ?? ''} />", '<TrackForm />'));
}

const only = process.argv[2];
for (const [slug, project] of Object.entries(projects)) {
  if (only && only !== slug) continue;
  if (!existsSync(join(project.source, 'package.json'))) { console.warn(`[export] skip ${slug}: ${project.source} not found`); continue; }
  const basePath = `${siteBase}/projects/${slug}/app`;
  const work = join(tmpdir(), 'rqke-next-export', slug);
  rmSync(work, { recursive: true, force: true });
  copyProject(project.source, work);
  symlinkSync(join(project.source, 'node_modules'), join(work, 'node_modules'), 'junction');
  writeNextConfig(work, basePath);
  prefixPublicPaths(work, basePath);
  project.patch?.(work);
  console.log(`[export] building ${slug} (basePath ${basePath})`);
  execSync(`node node_modules/next/dist/bin/next build ${project.buildArgs ?? ''}`, { cwd: work, stdio: 'inherit', env: { ...process.env, NEXT_TELEMETRY_DISABLED: '1' } });
  const target = join(root, 'public', 'projects', slug, 'app');
  rmSync(target, { recursive: true, force: true });
  cpSync(join(work, 'out'), target, { recursive: true });
  console.log(`[export] ${slug} → ${target}`);
}
